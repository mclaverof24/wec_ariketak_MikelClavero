// --- BERDINTASUN AHULA (Loose Equality: ==) ---
// Oharra: "==" eragileak balio motak berdintzen saiatzen da konparazioa egin aurretik.

console.log(5 == 5);      // true  -> Balio eta mota berdina (zenbakiak)
console.log(5 == "5");    // true  -> Testua ("5") zenbaki (5) bihurtzen du konparatzeko
console.log(1 == true);   // true  -> Boolearra (true) zenbaki (1) bihurtzen du
console.log(0 == false);  // true  -> Boolearra (false) zenbaki (0) bihurtzen du