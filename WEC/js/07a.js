let x = 10; // Hasierako balioa: 10

// --- GEHIKETA ETA ESLEIPENA (x = x + 2) ---
x += 2;
console.log(x); // 12 (10 + 2)

// --- KENKETA ETA ESLEIPENA (x = x - 2) ---
x -= 2;
console.log(x); // 10 (12 - 2)

// --- BIDERKETA ETA ESLEIPENA (x = x * 2) ---
x *= 2;
console.log(x); // 20 (10 * 2)

// --- ZATIKETA ETA ESLEIPENA (x = x / 2) ---
x /= 2;
console.log(x); // 10 (20 / 2)

// --- HONDARRA/MODULUA ETA ESLEIPENA (x = x % 3) ---
x %= 3;
console.log(x); // 1 (10 / 3 egitean, hondarra 1 da)

// --- BIDERKETA BERRIRO (x = x * 2) ---
x *= 2;
console.log(x); // 2 (1 * 2)